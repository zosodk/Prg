print("Hejsa\nJeg skal bruge to tal, fra dig\n")
tal1 = input("Tal nr 1: ")
tal2 = input("Tal nr 2: ")
print("Summen er: " + str(int(tal1) + int(tal2)) + "\n")
print("Forskellen er: " + str(int(tal1) - int(tal2)) + "\n")
print("Produktet er: " + str(int(tal1) * int(tal2)) + "\n")
print("Divisionen er: " + str(int(tal1) / int(tal2)) + "\n")
#Modulus er en heltalsdivision, der undersøger hvor mange gange tal2 går op i tal1 og returnerer resten
print("Modulus er: " + str(int(tal1) % int(tal2)) + "\n")

